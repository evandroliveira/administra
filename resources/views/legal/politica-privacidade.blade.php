    <h1 class="fw-bold text-primary mb-2">Política de Privacidade</h1>
    <p class="text-secondary mb-5">Última atualização: 16 de outubro de 2026</p>

    <p class="mb-4">
      A <strong>Evandro Informática</strong> ("nós") é responsável pelo desenvolvimento e operação do sistema
      <strong>Administrar</strong> ("sistema", "plataforma"). Esta Política de Privacidade descreve como coletamos,
      usamos, armazenamos, compartilhamos e protegemos os dados pessoais de visitantes do site institucional e de
      usuários cadastrados na plataforma, em conformidade com a Lei Geral de Proteção de Dados (Lei nº 13.709/2018 —
      LGPD).
    </p>

    <h2 class="h4 fw-bold text-primary mt-5 mb-3">1. Quem é o controlador dos dados</h2>
    <p class="mb-4">
      A Evandro Informática atua como controladora dos dados pessoais coletados no site institucional e durante o
      cadastro de empresas e usuários na plataforma. Em relação aos dados inseridos pelos clientes durante o uso do
      sistema (como cadastro de clientes, produtos e vendas), a empresa contratante do Administrar atua como
      controladora, e a Evandro Informática atua como operadora dos dados, processando-os apenas conforme as
      instruções e finalidades definidas pelo cliente contratante.
    </p>

    <h2 class="h4 fw-bold text-primary mt-5 mb-3">2. Quais dados coletamos</h2>
    <p class="mb-2">Coletamos os seguintes dados, conforme a interação com o site e a plataforma:</p>
    <ul class="mb-4">
      <li><strong>Dados de cadastro da empresa:</strong> razão social/nome, CPF ou CNPJ, e-mail, telefone e logotipo.</li>
      <li><strong>Dados de cadastro do usuário responsável:</strong> nome, nome de usuário, e-mail e senha (armazenada de forma criptografada).</li>
      <li><strong>Dados de cobrança e pagamento:</strong> processados pelo gateway de pagamentos parceiro (Asaas), responsável pela geração de cobranças, boletos e assinaturas recorrentes. Não armazenamos dados completos de cartão de crédito em nossos servidores.</li>
      <li><strong>Dados de navegação:</strong> endereço IP, tipo de navegador, páginas acessadas e cookies técnicos necessários ao funcionamento do site e da sessão autenticada.</li>
      <li><strong>Dados operacionais inseridos no sistema:</strong> cadastros de clientes, produtos, vendas, contas a pagar/receber e promissórias, inseridos pela empresa contratante durante o uso da plataforma.</li>
    </ul>

    <h2 class="h4 fw-bold text-primary mt-5 mb-3">3. Para que usamos os dados</h2>
    <ul class="mb-4">
      <li>Criar e manter contas de acesso ao sistema;</li>
      <li>Processar assinaturas, cobranças e emissão de boletos;</li>
      <li>Viabilizar as funcionalidades de gestão financeira, vendas, estoque e clientes contratadas;</li>
      <li>Enviar comunicações operacionais (confirmações, avisos de cobrança, suporte técnico);</li>
      <li>Cumprir obrigações legais e regulatórias;</li>
      <li>Garantir a segurança da plataforma e prevenir fraudes.</li>
    </ul>

    <h2 class="h4 fw-bold text-primary mt-5 mb-3">4. Compartilhamento de dados</h2>
    <p class="mb-2">Podemos compartilhar dados pessoais com os seguintes terceiros, estritamente para viabilizar o funcionamento do serviço:</p>
    <ul class="mb-4">
      <li><strong>Asaas</strong> — processamento de pagamentos, boletos e assinaturas recorrentes;</li>
      <li><strong>Hostinger</strong> — provedor de infraestrutura e hospedagem do sistema;</li>
      <li><strong>Autoridades públicas</strong> — quando exigido por lei, ordem judicial ou determinação de órgão regulador.</li>
    </ul>
    <p class="mb-4">Não vendemos nem alugamos dados pessoais a terceiros para fins de marketing.</p>

    <h2 class="h4 fw-bold text-primary mt-5 mb-3">5. Cookies</h2>
    <p class="mb-4">
      Utilizamos cookies estritamente necessários para manter sua sessão autenticada e garantir a segurança do
      sistema (como o token de proteção contra CSRF). Não utilizamos cookies de rastreamento publicitário de
      terceiros.
    </p>

    <h2 class="h4 fw-bold text-primary mt-5 mb-3">6. Armazenamento e segurança</h2>
    <p class="mb-4">
      Os dados são armazenados em servidores com acesso restrito e protegidos por práticas de segurança da
      informação, incluindo criptografia de senhas, conexão HTTPS e controle de acesso por perfil de usuário.
      Mantemos os dados pelo tempo necessário para cumprir as finalidades descritas nesta política ou conforme
      exigido por lei.
    </p>

    <h2 class="h4 fw-bold text-primary mt-5 mb-3">7. Seus direitos como titular dos dados</h2>
    <p class="mb-2">Nos termos da LGPD, você pode solicitar a qualquer momento:</p>
    <ul class="mb-4">
      <li>Confirmação da existência de tratamento de seus dados;</li>
      <li>Acesso, correção ou atualização de dados incompletos ou desatualizados;</li>
      <li>Anonimização, bloqueio ou eliminação de dados desnecessários ou tratados em desconformidade com a lei;</li>
      <li>Portabilidade dos dados a outro fornecedor de serviço;</li>
      <li>Revogação do consentimento e eliminação dos dados tratados com base nele;</li>
      <li>Informações sobre com quem compartilhamos seus dados.</li>
    </ul>
    <p class="mb-4">
      Para exercer esses direitos, entre em contato pelo e-mail
      <a href="mailto:administrativo@lojagerencia.com.br">administrativo@lojagerencia.com.br</a>.
    </p>

    <h2 class="h4 fw-bold text-primary mt-5 mb-3">8. Alterações nesta política</h2>
    <p class="mb-4">
      Esta Política de Privacidade pode ser atualizada periodicamente para refletir melhorias no sistema ou
      mudanças legais. A data da última atualização está sempre indicada no topo desta página.
    </p>

    <h2 class="h4 fw-bold text-primary mt-5 mb-3">9. Contato</h2>
    <p class="mb-5">
      Em caso de dúvidas sobre esta Política de Privacidade ou sobre o tratamento de seus dados pessoais, entre em
      contato com a Evandro Informática pelo e-mail
      <a href="mailto:administrativo@lojagerencia.com.br">administrativo@lojagerencia.com.br</a>.
    </p>
